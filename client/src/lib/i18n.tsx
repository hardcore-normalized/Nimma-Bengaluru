export type MsgKey = keyof typeof EN;

interface LangCtx {
  t: (k: MsgKey, vars?: Record<string, string | number>) => string;
}

const Ctx = createContext<LangCtx>(null as any);

export function LangProvider({ children }: { children: ReactNode }) {
  const t = (k: MsgKey, vars?: Record<string, string | number>) => {
    let s = EN[k] || k;
    if (vars) for (const [vk, vv] of Object.entries(vars)) s = s.replace(`{${vk}}`, String(vv));
    return s;
  };
  return <Ctx.Provider value={{ t }}>{children}</Ctx.Provider>;
}

export const useLang = () => useContext(Ctx);
